#!/usr/bin/env python
"""
findcenter_sdf.py

Read an SDF file (V2000 molfile), compute the centroid and bounding box
of the (first) molecule, and write an AutoDock Vina config file
(vina_center.conf) with center and box size.

Usage:
    python findcenter_sdf.py -i ligand.sdf
    python findcenter_sdf.py -i ligand.sdf -o vina_center.conf --padding 4.0
    python findcenter_sdf.py -i multi.sdf -m 2

Author: rewritten from original findcenter.py
"""

from os.path import basename, splitext
from math import sqrt
import argparse
import sys


class Point:
    def __init__(self, x, y, z):
        self.x = x
        self.y = y
        self.z = z

    def distance(self, other):
        return sqrt(
            (self.x - other.x) ** 2 +
            (self.y - other.y) ** 2 +
            (self.z - other.z) ** 2
        )

    def length(self):
        return sqrt(self.x ** 2 + self.y ** 2 + self.z ** 2)

    def __str__(self):
        return f"{self.x},{self.y},{self.z}"


class Atom:
    def __init__(self, name, x, y, z, element="", line=""):
        self.name = name
        self.point = Point(float(x), float(y), float(z))
        self.element = element
        self.line = line

    def getPoint(self):
        return self.point

    def getLine(self):
        return self.line

    def __str__(self):
        return self.line


def read_sdf_molecules(path):
    """
    Yield lists of Atom objects, one list per molecule in the SDF file.
    Only V2000 molfiles are supported (the common case).
    """
    with open(path, "r") as f:
        lines = f.readlines()

    i = 0
    n = len(lines)
    while i < n:
        # Skip leading blank lines / non-molfile lines until a counts line
        # A counts line is the 4th line of a molfile block; we detect it
        # by trying to parse the first 3 fields as integers.
        if i + 3 >= n:
            break

        # Heuristic: molfile header is 3 lines, 4th is counts line
        counts_line = lines[i + 3]
        parts = counts_line.split()
        if len(parts) < 2:
            i += 1
            continue
        try:
            natoms = int(parts[0])
            nbonds = int(parts[1])
        except ValueError:
            i += 1
            continue

        # Check V2000
        if "V2000" not in counts_line and "v2000" not in counts_line:
            # Try V3000? Not supported here; skip this block.
            # Advance past "M  END" if present
            j = i + 4
            while j < n and "M  END" not in lines[j]:
                j += 1
            i = j + 1
            continue

        atoms = []
        start = i + 4
        end = start + natoms
        if end > n:
            break

        for k in range(start, end):
            aline = lines[k]
            # V2000 atom line: xxxxx.xxxxyyyyy.yyyyzzzzz.zzzz aaa ...
            # Fixed columns are standard, but we also fall back to split.
            try:
                x = float(aline[0:10])
                y = float(aline[10:20])
                z = float(aline[20:30])
                elem = aline[31:34].strip()
            except ValueError:
                parts = aline.split()
                if len(parts) < 4:
                    continue
                x, y, z = float(parts[0]), float(parts[1]), float(parts[2])
                elem = parts[3] if len(parts) > 3 else ""

            atoms.append(Atom(elem, x, y, z, elem, aline.rstrip("\n")))

        yield atoms

        # Advance to next molecule: skip bonds and properties until "$$$$"
        j = end
        while j < n and "$$$$" not in lines[j]:
            j += 1
        i = j + 1


def compute_centroid_and_box(atoms):
    if not atoms:
        return None

    x = y = z = 0.0
    maxx = maxy = maxz = -float("inf")
    minx = miny = minz = float("inf")

    for atom in atoms:
        pt = atom.point
        x += pt.x
        y += pt.y
        z += pt.z
        maxx = max(maxx, pt.x)
        minx = min(minx, pt.x)
        maxy = max(maxy, pt.y)
        miny = min(miny, pt.y)
        maxz = max(maxz, pt.z)
        minz = min(minz, pt.z)

    count = len(atoms)
    cx, cy, cz = x / count, y / count, z / count

    return {
        "centroid": (cx, cy, cz),
        "min": (minx, miny, minz),
        "max": (maxx, maxy, maxz),
        "count": count,
    }


def write_vina_conf(path, center, size):
    cx, cy, cz = center
    sx, sy, sz = size
    with open(path, "w") as f:
        f.write("# AutoDock Vina configuration (generated by findcenter_sdf.py)\n")
        f.write("\n")
        f.write("center_x = %.3f\n" % cx)
        f.write("center_y = %.3f\n" % cy)
        f.write("center_z = %.3f\n" % cz)
        f.write("\n")
        f.write("size_x = %.3f\n" % sx)
        f.write("size_y = %.3f\n" % sy)
        f.write("size_z = %.3f\n" % sz)
        f.write("\n")
        # Optional sensible defaults for Vina
        f.write("# exhaustiveness = 8\n")
        f.write("# num_modes = 9\n")
        f.write("# energy_range = 3\n")


def main():
    parser = argparse.ArgumentParser(
        description="Compute Vina box center/size from an SDF file."
    )
    parser.add_argument(
        "-i", dest="structure", required=True,
        help="Input file in .sdf format (V2000 molfile)"
    )
    parser.add_argument(
        "-o", dest="output", default="vina_center.conf",
        help="Output Vina config file (default: vina_center.conf)"
    )
    parser.add_argument(
        "-m", dest="molecule", type=int, default=1,
        help="Which molecule in the SDF to use (1-based, default: 1)"
    )
    parser.add_argument(
        "--padding", dest="padding", type=float, default=4.0,
        help="Padding added to each side of the bounding box in Angstroms (default: 4.0)"
    )
    parser.add_argument(
        "-e", dest="Even", action="store_true",
        help="Round box dimensions to even integers (legacy option)"
    )
    args = parser.parse_args()

    filename = splitext(basename(args.structure))[0]
    print(f"Processing file: {filename}")

    # Read molecules
    molecules = list(read_sdf_molecules(args.structure))
    if not molecules:
        print("ERROR: No valid V2000 molfile found in the input SDF.", file=sys.stderr)
        sys.exit(1)

    if args.molecule < 1 or args.molecule > len(molecules):
        print(
            f"ERROR: molecule index {args.molecule} out of range "
            f"(file contains {len(molecules)} molecule(s)).",
            file=sys.stderr,
        )
        sys.exit(1)

    atoms = molecules[args.molecule - 1]
    if not atoms:
        print("ERROR: Selected molecule has no atoms.", file=sys.stderr)
        sys.exit(1)

    info = compute_centroid_and_box(atoms)
    cx, cy, cz = info["centroid"]
    (minx, miny, minz) = info["min"]
    (maxx, maxy, maxz) = info["max"]

    # Box size = extent + 2*padding
    sx = (maxx - minx) + 2.0 * args.padding
    sy = (maxy - miny) + 2.0 * args.padding
    sz = (maxz - minz) + 2.0 * args.padding

    # Minimum size to avoid degenerate boxes
    min_box = 10.0
    sx = max(sx, min_box)
    sy = max(sy, min_box)
    sz = max(sz, min_box)

    if args.Even:
        sx = int(round(sx))
        sy = int(round(sy))
        sz = int(round(sz))
        if sx % 2:
            sx += 1
        if sy % 2:
            sy += 1
        if sz % 2:
            sz += 1
        sx, sy, sz = float(sx), float(sy), float(sz)

    print(f"Atoms in selected molecule: {info['count']}")
    print("Centroid is:")
    print(f"{cx:.3f}, {cy:.3f}, {cz:.3f}")
    print("\nCoordinate ranges:")
    print(f"X: {minx:.3f} to {maxx:.3f}")
    print(f"Y: {miny:.3f} to {maxy:.3f}")
    print(f"Z: {minz:.3f} to {maxz:.3f}")
    print(f"\nBox size (with padding {args.padding} A):")
    print(f"size_x = {sx:.3f}")
    print(f"size_y = {sy:.3f}")
    print(f"size_z = {sz:.3f}")

    write_vina_conf(args.output, (cx, cy, cz), (sx, sy, sz))
    print(f"\nWrote Vina config to: {args.output}")
    print("\nYou can run Vina with:")
    print(f"    vina --receptor receptor.pdbqt --ligand ligand.pdbqt --config {args.output}")


if __name__ == "__main__":
    main()
